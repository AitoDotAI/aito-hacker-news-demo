"""Publish an evaluation run to the page and the README.

The accuracy numbers the demo shows must come from a run, never from a
hand edit. This script takes the eval report for the corpus production
serves (plus optional same-window reports for older corpora) and writes:

  frontend/lib/eval-summary.json   — imported by the page at build time
  README.md                        — the block between the eval markers
  assets/teaser.html               — the data-eval numbers (then ./do screenshot-teaser)

Usage:
    uv run python -m scripts.publish_eval data/eval-report-v3.json \\
        --compare "previous corpus=data/eval-report-v2-samewindow.json" \\
        --compare "2023 corpus=data/eval-report-v1-samewindow-oct.json"

Re-run it whenever evaluate.py is re-run; commit both outputs together.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SUMMARY = ROOT / "frontend" / "lib" / "eval-summary.json"
README = ROOT / "README.md"
TEASER = ROOT / "assets" / "teaser.html"
BEGIN = "<!-- eval:begin (generated by scripts/publish_eval.py; do not edit) -->"
END = "<!-- eval:end -->"

# Calibration bins thinner than this are reported as "too few to say".
MIN_BIN_N = 20

ABLATION_KEYS = {
    "title only": "title",
    "domain only": "domain",
    "title + domain": "title_domain",
    "hour only": "hour",
    "length only": "length",
    "shipped, domain posts": "shipped_domain",
    "shipped minus time": "shipped_no_time",
    "title + domain + flags": "title_domain_flags",
}


def summarise(report: dict, source: str, comparisons: list[tuple[str, dict, str]]) -> dict:
    full = report["full_model"]
    bins = [
        {"predicted": b["mean_predicted"], "observed": b["observed"], "n": b["n"]}
        for b in full["calibration"]
    ]
    abl = report.get("ablation") or {}
    why = report.get("why_invariant") or {}
    return {
        "source": source,
        "corpus": {k: report["corpus"][k] for k in ("rows", "oldest", "newest")},
        "holdout": report["holdout"],
        "shipped": {
            "auc": full["auc"],
            "auc_ci95": full.get("auc_ci95"),
            "floored_share": full.get("floored_share"),
            "n_scored": full["n_scored"],
            "lift": full["decile"]["lift"],
            "top_decile_rate": full["decile"]["top_decile_rate"],
            "bottom_decile_rate": full["decile"]["bottom_decile_rate"],
        },
        "calibration": bins,
        "calibration_min_n": MIN_BIN_N,
        "calibration_out_of_sample": _disjoint(
            report.get("calibration_fit_window"), report["holdout"]),
        "ablation": {
            ABLATION_KEYS[name]: {
                "auc": a["auc"], "auc_ci95": a.get("auc_ci95"),
                "lift": a["decile"]["lift"], "n": a["n"],
                "vs_shipped": a.get("vs_shipped"),
            }
            for name, a in abl.items() if name in ABLATION_KEYS
        },
        "comparisons": [
            {
                "label": label,
                "source": src,
                "corpus_rows": r["corpus"]["rows"],
                "corpus_oldest": r["corpus"]["oldest"],
                "corpus_newest": r["corpus"]["newest"],
                "auc": r["full_model"]["auc"],
                "lift": r["full_model"]["decile"]["lift"],
                "same_holdout": (
                    r["holdout"]["start"] == report["holdout"]["start"]
                    and r["holdout"]["end"] == report["holdout"]["end"]
                    and r["holdout"]["n"] == report["holdout"]["n"]
                ),
            }
            for label, r, src in comparisons
        ],
        "why_invariant": {
            "checked": why.get("checked", 0),
            "failures": len(why.get("failures", [])),
        },
    }


def _ci(ci: list[float] | None) -> str:
    return f"{ci[0]:.3f}-{ci[1]:.3f}" if ci else "n/a"


def _disjoint(fit_window: list[str] | None, holdout: dict) -> bool:
    """True iff the calibration was fitted on days this holdout doesn't touch."""
    if not fit_window:
        return False
    fit_start, fit_end = fit_window
    h_start, h_end = holdout["start"][:10], holdout["end"][:10]
    return fit_end <= h_start or h_end <= fit_start


def readme_block(s: dict) -> str:
    h, sh, c = s["holdout"], s["shipped"], s["corpus"]
    lines = [
        BEGIN,
        "",
        f"Corpus: {c['rows']:,} submissions, {c['oldest'][:10]} to {c['newest'][:10]}. "
        f"Holdout: {h['n']:,} submissions posted {h['start'][:10]} to {h['end'][:10]}, "
        f"after the corpus ends, base rate {h['base_rate']:.1%}. Source: `{s['source']}`.",
        "",
        "| | AUC (95% CI) | top-decile lift | vs. shipped, same posts (95% CI) |",
        "|---|---|---|---|",
        f"| **as shipped** | **{sh['auc']:.3f}** ({_ci(sh.get('auc_ci95'))}) | {sh['lift']:.2f}x | |",
    ]
    names = {"title": "title only", "domain": "domain only",
             "title_domain": "title + domain", "hour": "posting hour only",
             "length": "title length only",
             "shipped_domain": "as shipped, posts with a domain",
             "shipped_no_time": "as shipped, without posting time",
             "title_domain_flags": "title + domain + Show/Ask flags"}
    for key, label in names.items():
        a = s["ablation"].get(key)
        if a:
            d = a.get("vs_shipped") or {}
            delta = (f"{d['delta']:+.3f} ({d['lo']:+.3f} to {d['hi']:+.3f})"
                     if d.get("n") else "")
            lines.append(f"| {label} | {a['auc']:.3f} ({_ci(a.get('auc_ci95'))}) | "
                         f"{a['lift']:.2f}x | {delta} |")
    oos = ("checked on posts the calibration was not fitted on"
           if s["calibration_out_of_sample"] else
           "IN-SAMPLE: the calibration was fitted on this same holdout")
    lines += ["", f"Calibration, predicted vs. what happened ({oos}):", "",
              "| predicted | observed | n |", "|---|---|---|"]
    for b in s["calibration"]:
        note = "" if b["n"] >= s["calibration_min_n"] else " (too few to say)"
        lines.append(f"| {b['predicted']:.1%} | {b['observed']:.1%} | {b['n']}{note} |")
    if s["comparisons"]:
        lines += ["", "Same holdout scored against older corpora:", "",
                  "| corpus | rows | ends | AUC |", "|---|---|---|---|"]
        lines.append(f"| current | {c['rows']:,} | {c['newest'][:10]} | {sh['auc']:.3f} |")
        for cmp in s["comparisons"]:
            flag = "" if cmp["same_holdout"] else " (different holdout!)"
            lines.append(f"| {cmp['label']} | {cmp['corpus_rows']:,} | "
                         f"{cmp['corpus_newest'][:10]} | {cmp['auc']:.3f}{flag} |")
    w = s["why_invariant"]
    lines += ["", f"`$why` invariant: {w['checked']} predictions checked, "
                  f"{w['failures']} failure(s).", "", END]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("report", help="eval report for the corpus production serves")
    ap.add_argument("--compare", action="append", default=[], metavar="LABEL=PATH",
                    help="same-window report for an older corpus (repeatable)")
    args = ap.parse_args(argv)

    report = json.loads(Path(args.report).read_text())
    if report.get("why_invariant", {}).get("failures"):
        ap.error("this run failed the $why invariant; fix that before publishing")
    comparisons = []
    for spec in args.compare:
        label, _, path = spec.partition("=")
        comparisons.append((label, json.loads(Path(path).read_text()), path))

    summary = summarise(report, args.report, comparisons)
    for cmp in summary["comparisons"]:
        if not cmp["same_holdout"]:
            print(f"warning: {cmp['label']} was scored on a different holdout; "
                  f"its AUC is not comparable", file=sys.stderr)

    SUMMARY.write_text(json.dumps(summary, indent=2) + "\n")
    print(f"wrote {SUMMARY.relative_to(ROOT)}")

    # The teaser (landing thumbnail + og:image) marks each number with a
    # data-eval attribute; rewrite their contents in place.
    values = {
        "holdout_n": f"{summary['holdout']['n']:,}",
        "corpus_k": f"{round(summary['corpus']['rows'], -3):,}",
        "auc": f"{summary['shipped']['auc']:.3f}",
        "lift": f"{summary['shipped']['lift']:.2f}",
    }
    teaser = TEASER.read_text()
    for key, val in values.items():
        teaser = re.sub(rf'(data-eval="{key}">)[^<]*(<)', rf"\g<1>{val}\g<2>", teaser)
    TEASER.write_text(teaser)
    print(f"updated {TEASER.relative_to(ROOT)} (re-render with ./do screenshot-teaser)")

    text = README.read_text()
    block = readme_block(summary)
    if BEGIN in text and END in text:
        text = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), lambda _: block,
                      text, flags=re.S)
        README.write_text(text)
        print(f"updated {README.relative_to(ROOT)}")
    else:
        print(f"README has no eval markers; add\n{BEGIN}\n{END}\nwhere the table goes",
              file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
